import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp, readFile, rm, writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {createRequire} from 'node:module';
import {EDLSchema} from '../shared/types';
import {evaluateRender,generateDemoAssets,hashFile,probeMedia,renderVideo,subtitlesFor,sampleActionFrames} from '../server/media';

test('real media: ingest, silent-track normalization, subtitles, render, cache and output QA', {timeout:180_000}, async()=>{
  const directory=await mkdtemp(path.join(tmpdir(),'cutflow-media-'));
  try {
    const assets=await generateDemoAssets(path.join(directory,'assets'));
    assert.equal(assets.length,3);
    assert.equal(assets[2].has_audio,false);
    assert.equal(assets[0].shots[0].evidence.type,'demo');
    assert.equal(await hashFile(assets[0].file_path),assets[0].sha256);
    const samples=await sampleActionFrames(assets[0].file_path,assets[0].duration_ms,path.join(directory,'action-frames'));
    assert(samples.length>=4&&samples.length<=16);
    assert.equal(samples[0].time_ms,0);assert.equal(samples.at(-1)!.time_ms,assets[0].duration_ms-100);
    assert(samples.every((sample,i)=>!i||sample.time_ms>samples[i-1].time_ms));
    for(const sample of samples)assert((await readFile(sample.path)).byteLength>100);
    const edl=EDLSchema.parse({schema_version:'1.0',version:1,clips:[assets[0],assets[2]].map((a,i)=>({id:`clip${i}`,asset_id:a.id,start_ms:100,end_ms:800,purpose:'测试媒体管线',caption:i===0?'中文字幕 100% "引用"':'无音轨素材',evidence:a.shots[0].evidence})),aspect_ratio:'16:9',resolution:'1080p',fps:30,title:'DEMO 测试',cta:'测试结束',audio_gain:0.5,subtitles:true});
    const before=await hashFile(assets[0].file_path);
    const result=await renderVideo(edl,assets,path.join(directory,'v1'),{quality:'preview'});
    assert.equal(result.renderer,'ffmpeg');
    assert.equal(result.width,1280);assert.equal(result.height,720);
    assert.equal((await probeMedia(result.video_path)).has_audio,true);
    assert.equal(result.cache_hits,0);
    assert.equal(await readFile(result.subtitle_path,'utf8'),subtitlesFor(edl));
    assert.match(await readFile(result.subtitle_path,'utf8'),/00:00:00,700 --> 00:00:01,400/);
    const report=await evaluateRender(result,edl,'preview');
    assert.equal(report.passed,true,JSON.stringify(report));
    assert.equal(report.checks.find(c=>c.name==='内容与视觉人工审核')?.status,'manual');
    const cached=await renderVideo({...edl,version:2},assets,path.join(directory,'v2'),{quality:'preview'});
    assert.equal(cached.cache_hits,2);
    const hidden=await renderVideo({...edl,subtitles:false},assets,path.join(directory,'hidden'),{quality:'preview'});
    const clean=await renderVideo({...edl,subtitles:false,title:'',cta:'',clips:edl.clips.map(c=>({...c,caption:''}))},assets,path.join(directory,'clean'),{quality:'preview'});
    assert.equal(await readFile(hidden.subtitle_path,'utf8'),'');
    assert.equal(clean.cache_hits,2,'disabled text omits titles, CTA and captions from the actual rendered segments');
    const ffmpeg=createRequire(import.meta.url)('ffmpeg-static');
    const decodedHash=(file:string,stream:string)=>execFileSync(ffmpeg,['-v','error','-i',file,'-map',stream,'-f','hash','-hash','sha256','-'],{encoding:'utf8'});
    assert.equal(decodedHash(hidden.video_path,'0:v'),decodedHash(clean.video_path,'0:v'));
    assert.notEqual(decodedHash(hidden.video_path,'0:v'),decodedHash(result.video_path,'0:v'));
    assert.equal(decodedHash(hidden.video_path,'0:a'),decodedHash(result.video_path,'0:a'),'hiding text leaves audio unchanged');
    const localAudio=await renderVideo({...edl,clips:edl.clips.map((c,i)=>i===0?{...c,audio_gain:0}:c)},assets,path.join(directory,'local-audio'),{quality:'preview'});
    assert.equal(localAudio.cache_hits,1,'local volume invalidates only the selected clip');
    assert.equal(decodedHash(localAudio.video_path,'0:v'),decodedHash(result.video_path,'0:v'),'local mute does not change pixels');
    assert.notEqual(decodedHash(localAudio.video_path,'0:a'),decodedHash(result.video_path,'0:a'),'clip gain changes the rendered audio');
    const changed=await renderVideo({...edl,version:3,clips:edl.clips.map((clip,index)=>index===0?{...clip,caption:'已修改的字幕'}:clip)},assets,path.join(directory,'v3'),{quality:'preview'});
    assert.equal(changed.cache_hits,1,'only the changed clip invalidates its cache');
    const finalEdl={...edl,aspect_ratio:'9:16' as const,clips:[{...edl.clips[0],end_ms:400}]};
    const final=await renderVideo(finalEdl,assets,path.join(directory,'final'),{quality:'final'});
    assert.equal(final.width,1080);assert.equal(final.height,1920);
    assert.equal((await evaluateRender(final,finalEdl,'final')).passed,true);
    const uneven={...edl,clips:[335,1171,606,3642,927,171].map((start,i)=>({...edl.clips[i%2],id:`uneven-${i}`,start_ms:start,end_ms:start+[533,959,259,988,817,447][i]}))};
    const fractional=await renderVideo(uneven,assets,path.join(directory,'fractional'),{quality:'preview'});
    const probe=createRequire(import.meta.url)('ffprobe-static').path;
    const frames=JSON.parse(execFileSync(probe,['-v','error','-select_streams','v:0','-show_entries','stream=nb_frames','-of','json',fractional.video_path],{encoding:'utf8'})).streams[0].nb_frames;
    assert.equal(Number(frames),uneven.clips.reduce((n,c)=>n+Math.round((c.end_ms-c.start_ms)*uneven.fps/1000),0),'fractional source cuts must not lose frames against audio and SRT timing');
    assert.equal((await evaluateRender(fractional,uneven,'preview')).passed,true);
    await assert.rejects(()=>probeMedia('https://example.com/video.mp4'),/本地绝对路径/);
    await assert.rejects(()=>renderVideo(edl,assets,path.join(directory,'unsupported'),{quality:'preview',renderer:'unknown'}),/不支持的渲染器/);
    assert.equal(await hashFile(assets[0].file_path),before,'original media remains unmodified');
    await assert.rejects(()=>renderVideo({...edl,clips:[{...edl.clips[0],asset_id:'untrusted'}]},assets,path.join(directory,'invalid'),{quality:'preview'}),/未授权素材/);
    const controller=new AbortController();controller.abort();
    await assert.rejects(()=>renderVideo(edl,assets,path.join(directory,'cancelled'),{quality:'preview',signal:controller.signal}),{name:'AbortError'});
    const corrupt=path.join(directory,'broken.mp4');await writeFile(corrupt,'not a video');
    const badReport=await evaluateRender({...result,video_path:corrupt},edl,'preview');
    assert.equal(badReport.passed,false);
    assert(badReport.issues.some(i=>i.code==='PROBE_FAILED'));
    assert(badReport.issues.some(i=>i.code==='DECODE_FAILED'));
  }finally{await rm(directory,{recursive:true,force:true});}
});
